import { expect, test } from 'bun:test'
import { dispatchComposerEditCommand } from './composer/contenteditable-control'
import { createSidePaneComposerFixture } from './test-support/side-pane-composer-fixture'

test('retained editors preserve DOM, selection, undo history, quotes and attachment ownership across hiding and moving', async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('retained-editor', 'right')
    f.setText('right', 'Owner question')
    f.window.klausSideComposerAddSelection('Structured parent context', 'right')
    const input = f.input('right'), control = f.controls.get(input)
    control.replaceRange(input.value.length, input.value.length, ' after quote', 'insertText')
    f.addFile('right', 'owned.txt')
    input.focus()
    input.setSelectionRange(2, 5)
    const root = input.closest('[data-side-pane]')
    const quote = input.querySelector('.kls-inline-quote')
    const document = control.snapshotDocument(), tokens = control.readTokens()
    const revision = control.revision, generation = control.historyGeneration
    const preview = root.querySelector('[data-side-local-id="side-previews"]')
    const attachment = f.calls.previews.get(preview)!.find(file => file.file?.name === 'owned.txt')
    const runtime = f.vmApi.sidePaneRuntimes.get('right'), messages = runtime.messagesEl
    const controller = f.scrollControllers.find(candidate => !candidate.destroyed && candidate.scrollEl === messages)!
    expect(controller).toBeDefined()
    expect(quote).not.toBeNull()
    expect(tokens.some((token: any) => token.data?.text === 'Structured parent context')).toBe(true)
    expect(attachment.uploading).toBe(true)
    expect(runtime.retainsAttachment(attachment)).toBe(true)
    await f.window.klausSideSurfaceActivate('unrelated-editor', 'right')
    f.setText('right', 'Independent draft')
    expect(root.hidden).toBe(true)
    expect(root.isConnected).toBe(true)
    expect(f.vmApi.sidePaneRuntimes.get('retained:retained-editor')).toBe(runtime)
    expect(f.vmApi.sidePaneRuntimes.get('right').retainsAttachment(attachment)).toBe(false)
    const unrelatedInput = f.input('right')
    expect(f.vmApi.sidePaneRuntimes.get('right').messagesEl).not.toBe(messages)
    expect(controller.destroyed).toBe(false)
    await f.window.klausSideSurfaceActivate('retained-editor', 'right')
    expect(f.input('right')).toBe(input)
    expect(f.controls.get(input)).toBe(control)
    expect(input.querySelector('.kls-inline-quote')).toBe(quote)
    expect(control.snapshotDocument()).toEqual(document)
    expect(control.readTokens()).toEqual(tokens)
    expect(control.revision).toBe(revision)
    expect(control.historyGeneration).toBe(generation)
    expect([input.selectionStart, input.selectionEnd]).toEqual([2, 5])
    expect(runtime.messagesEl).toBe(messages)
    f.window.klausSideSurfaceClear('right')
    expect(root.hidden).toBe(true)
    expect(root.isConnected).toBe(true)
    expect(f.vmApi.sidePaneRuntimes.get('retained:retained-editor')).toBe(runtime)
    await f.window.klausSideSurfaceActivate('retained-editor', 'right')
    expect(f.input('right')).toBe(input)
    expect(control.historyGeneration).toBe(generation)
    expect([input.selectionStart, input.selectionEnd]).toEqual([2, 5])
    await f.window.klausSideSurfaceMove('retained-editor', 'left')
    expect(f.input('left')).toBe(input)
    expect(input.closest('[id$="composer-host"]').id).toBe('left-side-composer-host')
    expect(runtime.messagesEl).toBe(messages)
    expect(messages.parentElement.id).toBe('left-side-messages')
    expect(controller.destroyed).toBe(false)
    expect(f.scrollControllers.filter(candidate => !candidate.destroyed && candidate.scrollEl === messages)).toEqual([controller])
    expect(control.snapshotDocument()).toEqual(document)
    expect([input.selectionStart, input.selectionEnd]).toEqual([2, 5])
    expect(f.calls.previews.get(preview)!.find(file => file.file?.name === 'owned.txt')).toBe(attachment)
    expect(runtime.retainsAttachment(attachment)).toBe(true)
    expect([...f.vmApi.sidePaneRuntimes.values()].filter(candidate => candidate === runtime)).toHaveLength(1)
    input.focus()
    expect(dispatchComposerEditCommand(f.document, 'undo')).toBe(true)
    expect(control.snapshotDocument()).not.toEqual(document)
    expect(dispatchComposerEditCommand(f.document, 'redo')).toBe(true)
    expect(control.snapshotDocument()).toEqual(document)
    await f.window.klausSideSurfaceActivate('unrelated-editor', 'right')
    expect(f.input('right')).toBe(unrelatedInput)
    expect(f.input('right').value).toBe('Independent draft')
    f.uploads.get('owned.txt')!.resolve({ path: '/uploads/owned.txt', name: 'owned.txt', type: 'text/plain' })
    await f.settle()
    expect(attachment.uploading).toBe(false)
    expect(attachment.uploadPath).toBe('/uploads/owned.txt')
    expect(f.input('right').value).toBe('Independent draft')
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions.map(call => call.id)).toEqual(['retained-editor'])
    expect(f.calls.submissions[0].payload.files).toContain(attachment)
    expect(f.calls.submissions[0].payload.files.some((file: any) => file.text === 'Structured parent context')).toBe(true)
  } finally { await f.destroy() }
})

test('bound runtime changes update Stop and Continue synchronously without a polling timer', async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('runtime-owner', 'left')
    await f.window.klausSideSurfaceActivate('runtime-other', 'right')
    const left = f.button('left') as HTMLButtonElement, right = f.button('right') as HTMLButtonElement
    f.setRuntime('runtime-owner', { running: true, activeTurnId: 'turn-owner' })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_stop')
    expect(left.disabled).toBe(false)
    expect(left.hasAttribute('title')).toBe(false)
    expect(right.classList.contains('busy')).toBe(false)
    left.click()
    expect(f.calls.stops).toEqual(['runtime-owner'])
    f.stopping.add('runtime-owner')
    f.setRuntime('runtime-owner', { stopRequestedAt: 42 })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_stopping')
    expect(left.disabled).toBe(true)
    f.stopping.delete('runtime-owner')
    f.setRuntime('runtime-owner', { running: false, lastTerminalStatus: 'interrupted', activeTurnId: null })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_continue')
    expect(left.disabled).toBe(false)
    expect(right.getAttribute('aria-label')).toBe('submit_tooltip_send')
    f.continuing.add('runtime-owner')
    f.setRuntime('runtime-owner', { continuedAt: 43 })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_continuing')
    expect(left.disabled).toBe(true)
    f.continuing.delete('runtime-owner')
    f.setRuntime('runtime-owner', { running: true, lastTerminalStatus: null, activeTurnId: 'turn-next' })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_stop')
    f.setText('left', 'Next instruction')
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_queue')
    f.setText('left', '')
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_stop')
    await f.window.klausSideSurfaceMove('runtime-owner', 'right')
    expect(f.button('right')).toBe(left)
    f.setRuntime('runtime-other', { running: true })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_stop')
    f.setRuntime('runtime-owner', { running: false, lastTerminalStatus: 'failed' })
    expect(left.getAttribute('aria-label')).toBe('submit_tooltip_continue')
    left.click()
    await f.settle()
    expect(f.calls.submissions.map(call => call.id)).toEqual(['runtime-owner'])
    expect(f.intervalCalls()).toBe(0)
  } finally { await f.destroy() }
})

test('two pane composers keep sends, queues, models and draft transfer bound to their own sessions', async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('side-left', 'left')
    await f.window.klausSideSurfaceActivate('side-right', 'right')
    await f.settle()
    expect(f.window.currentSessionId).toBe('parent')
    expect(f.input('left')).not.toBe(f.input('right'))
    expect(f.modelPickers.get('left-side-composer-host').options.getSessionId()).toBe('side-left')
    expect(f.modelPickers.get('side-composer-host').options.getSessionId()).toBe('side-right')
    expect(f.permissionPickers.get('left-side-composer-host').sessionId()).toBe('side-left')
    expect(f.permissionPickers.get('side-composer-host').sessionId()).toBe('side-right')
    f.setText('left', 'Left question')
    f.setText('right', 'Right draft')
    expect(f.input('left').value).toBe('Left question')
    expect((f.button('left') as any).disabled).toBe(false)
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions.map(call => [call.id, call.payload.text])).toEqual([['side-left', 'Left question']])
    expect(f.input('right').value).toBe('Right draft')
    f.running.add('side-right')
    f.button('right').click()
    await f.settle()
    expect(f.calls.queues).toEqual(['side-right'])
    expect(f.calls.submissions).toHaveLength(1)
    f.setText('left', 'Moved draft')
    const originalSlot = f.document.querySelector('[data-sideid="side-left"]')
    await f.window.klausSideSurfaceMove('side-left', 'right')
    await f.settle()
    expect(f.window.klausSideSurfaceSessionId('left')).toBeNull()
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('side-left')
    expect(f.input('right').value).toBe('Moved draft')
    expect(f.document.querySelector('[data-sideid="side-left"]')).toBe(originalSlot)
    expect(originalSlot!.parentElement!.id).toBe('side-messages')
    await f.window.klausSideSurfaceActivate('side-right', 'left')
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('side-left')
    expect(f.window.klausSideSurfaceSessionId('left')).toBe('side-right')
    f.window.klausSideSurfaceShowParent()
    expect(f.document.getElementById('main')!.dataset.leftSideSession).toBeUndefined()
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('side-left')
  } finally { await f.destroy() }
})


for (const failed of [false, true]) test(`an upload settling after a pane move remains owned by the moved draft: failure=${failed}`, async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('moving', 'left')
    await f.window.klausSideSurfaceActivate('other', 'right')
    f.setText('left', 'Question with a file')
    f.setText('right', 'Unrelated draft')
    f.addFile('left', 'pending.txt')
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions).toHaveLength(0)
    await f.window.klausSideSurfaceMove('moving', 'right')
    await f.window.klausSideSurfaceActivate('other', 'left')
    if (failed) f.uploads.get('pending.txt')!.reject(new Error('Upload failed'))
    else f.uploads.get('pending.txt')!.resolve({ path: '/uploads/file', name: 'pending.txt', type: 'text/plain' })
    await f.settle()
    expect(f.calls.submissions.map(call => call.id)).toEqual(['moving'])
    expect(f.calls.submissions[0].payload.files).toHaveLength(failed ? 0 : 1)
    expect(f.input('left').value).toBe('Unrelated draft')
    expect(f.window.klausSideSurfaceSessionId('left')).toBe('other')
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('moving')
  } finally { await f.destroy() }
})

test('a pending left draft promotes without replacing the active right draft or its quote', async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('right', 'right')
    f.setText('right', 'Right draft')
    f.window.klausSideComposerPrepare('pending-side-left', 'parent', 'left')
    f.setText('left', 'Left pending question')
    f.window.klausSideComposerAddSelection('Quoted parent context', 'left')
    expect((f.button('left') as any).disabled).toBe(true)
    await f.window.klausSideComposerPromote('pending-side-left', 'left')
    await f.window.klausSideSurfaceActivate('left', 'left')
    await f.settle()
    expect(f.input('right').value).toBe('Right draft')
    expect(f.input('left').value).toContain('Left pending question')
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions.map(call => call.id)).toEqual(['left'])
    expect(f.calls.submissions[0].payload.files[0].text).toBe('Quoted parent context')
    f.window.klausSideSurfaceRemove('left')
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('right')
    expect(f.input('right').value).toBe('Right draft')
    expect(f.document.getElementById('main')!.dataset.leftSideSession).toBeUndefined()
  } finally { await f.destroy() }
})
