import { expect, test } from 'bun:test'
import { createSidePaneComposerFixture } from './test-support/side-pane-composer-fixture'

test('two pane composers keep sends, queues, models and draft transfer bound to their own sessions', async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('side-left', 'left')
    await f.window.klausSideSurfaceActivate('side-right', 'right')
    await f.settle()
    expect(f.window.currentSessionId).toBe('parent')
    expect(f.input('left')).not.toBe(f.input('right'))
    expect(f.modelPickers.get('left-side-composer-host').options.getSessionId()).toBe('side-left')
    expect(f.modelPickers.get('side-composer-host').options.getSessionId()).toBe('side-right')
    expect(f.permissionPickers.get('left-side-composer-host').sessionId()).toBe('side-left')
    expect(f.permissionPickers.get('side-composer-host').sessionId()).toBe('side-right')
    f.setText('left', 'Left question')
    f.setText('right', 'Right draft')
    expect(f.input('left').value).toBe('Left question')
    expect((f.button('left') as any).disabled).toBe(false)
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions.map(call => [call.id, call.payload.text])).toEqual([['side-left', 'Left question']])
    expect(f.input('right').value).toBe('Right draft')
    f.running.add('side-right')
    f.button('right').click()
    await f.settle()
    expect(f.calls.queues).toEqual(['side-right'])
    expect(f.calls.submissions).toHaveLength(1)
    f.setText('left', 'Moved draft')
    const originalSlot = f.document.querySelector('[data-sideid="side-left"]')
    await f.window.klausSideSurfaceMove('side-left', 'right')
    await f.settle()
    expect(f.window.klausSideSurfaceSessionId('left')).toBeNull()
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('side-left')
    expect(f.input('right').value).toBe('Moved draft')
    expect(f.document.querySelector('[data-sideid="side-left"]')).toBe(originalSlot)
    expect(originalSlot!.parentElement!.id).toBe('side-messages')
    await f.window.klausSideSurfaceActivate('side-right', 'left')
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('side-left')
    expect(f.window.klausSideSurfaceSessionId('left')).toBe('side-right')
    f.window.klausSideSurfaceShowParent()
    expect(f.document.getElementById('main')!.dataset.leftSideSession).toBeUndefined()
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('side-left')
  } finally { await f.destroy() }
})


for (const failed of [false, true]) test(`an upload settling after a pane move remains owned by the moved draft: failure=${failed}`, async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('moving', 'left')
    await f.window.klausSideSurfaceActivate('other', 'right')
    f.setText('left', 'Question with a file')
    f.setText('right', 'Unrelated draft')
    f.addFile('left', 'pending.txt')
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions).toHaveLength(0)
    await f.window.klausSideSurfaceMove('moving', 'right')
    await f.window.klausSideSurfaceActivate('other', 'left')
    if (failed) f.uploads.get('pending.txt')!.reject(new Error('Upload failed'))
    else f.uploads.get('pending.txt')!.resolve({ path: '/uploads/file', name: 'pending.txt', type: 'text/plain' })
    await f.settle()
    expect(f.calls.submissions.map(call => call.id)).toEqual(['moving'])
    expect(f.calls.submissions[0].payload.files).toHaveLength(failed ? 0 : 1)
    expect(f.input('left').value).toBe('Unrelated draft')
    expect(f.window.klausSideSurfaceSessionId('left')).toBe('other')
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('moving')
  } finally { await f.destroy() }
})

test('a pending left draft promotes without replacing the active right draft or its quote', async () => {
  const f = createSidePaneComposerFixture()
  try {
    await f.window.klausSideSurfaceActivate('right', 'right')
    f.setText('right', 'Right draft')
    f.window.klausSideComposerPrepare('pending-side-left', 'parent', 'left')
    f.setText('left', 'Left pending question')
    f.window.klausSideComposerAddSelection('Quoted parent context', 'left')
    expect((f.button('left') as any).disabled).toBe(true)
    await f.window.klausSideComposerPromote('pending-side-left', 'left')
    await f.window.klausSideSurfaceActivate('left', 'left')
    await f.settle()
    expect(f.input('right').value).toBe('Right draft')
    expect(f.input('left').value).toContain('Left pending question')
    f.button('left').click()
    await f.settle()
    expect(f.calls.submissions.map(call => call.id)).toEqual(['left'])
    expect(f.calls.submissions[0].payload.files[0].text).toBe('Quoted parent context')
    f.window.klausSideSurfaceRemove('left')
    expect(f.window.klausSideSurfaceSessionId('right')).toBe('right')
    expect(f.input('right').value).toBe('Right draft')
    expect(f.document.getElementById('main')!.dataset.leftSideSession).toBeUndefined()
  } finally { await f.destroy() }
})
