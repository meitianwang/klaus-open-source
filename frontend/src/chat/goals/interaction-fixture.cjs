const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, mkdirSync, rmSync, writeFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { dirname, join, resolve } = require('node:path')
const { buildSync } = require('esbuild')

const directory = mkdtempSync(join(tmpdir(), 'klaus-goal-interactions-'))
app.setPath('userData', directory)
const htmlPath = resolve(process.argv[2] || 'dist/planning-ui-logs/interaction-fixture/index.html')
const assets = dirname(htmlPath)
mkdirSync(assets, { recursive: true })
buildSync({ entryPoints: [join(__dirname, 'interaction.fixture.tsx')], bundle: true, outfile: join(assets, 'fixture.js'), format: 'iife',
  platform: 'browser', target: 'chrome132', jsx: 'automatic', loader: { '.svg': 'dataurl', '.woff': 'dataurl', '.woff2': 'dataurl', '.ttf': 'dataurl' }, logLevel: 'warning' })
writeFileSync(htmlPath, '<!doctype html><meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><style>body{margin:0;padding:24px;font:14px system-ui;background:#fff;color:#111}#editor{height:380px;min-height:380px}#restricted-editor{height:260px;min-height:260px}#input-wrapper,#side-host{margin-top:24px}textarea{display:block;width:500px;height:80px}button{padding:8px}#composer-plus-menu{position:fixed;background:#fff;z-index:20}</style><script defer src="fixture.js"></script>')
let window
const pause = () => new Promise(resolvePause => setTimeout(resolvePause, 30))
async function read(expression) { return window.webContents.executeJavaScript(expression) }
async function until(expression) {
  const end = Date.now() + 10000
  while (Date.now() < end) { if (await read(expression)) return; await pause() }
  throw new Error(`Timed out waiting for ${expression}`)
}
async function key(keyCode, modifiers = []) {
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers })
  await pause()
}
async function snapshot() { return read('window.goalInteractionFixture.snapshot()') }
async function run() {
  await app.whenReady()
  window = new BrowserWindow({ width: 1000, height: 800, show: true, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } })
  window.webContents.on('console-message', (...args) => { const [, level, message] = args; if (level >= 3) console.error(message) })
  await window.loadFile(htmlPath)
  await until('window.goalInteractionFixture && document.querySelector("#editor .cm-content")')
  window.focus(); window.webContents.focus()
  await read('document.querySelector("#editor .cm-content").focus()')
  await key('A', [process.platform === 'darwin' ? 'meta' : 'control'])
  await window.webContents.insertText('/goal')
  await until('window.goalInteractionFixture.snapshot().text === "/goal"')
  for (const text of [' @file', ' $skill']) { await window.webContents.insertText(text); await pause(); assert.equal((await snapshot()).editorMenus, 0) }
  await key('Enter')
  await window.webContents.insertText('Second line')
  await until('window.goalInteractionFixture.snapshot().text === "/goal @file $skill\\nSecond line"')
  assert.deepEqual((await snapshot()).saves, [])
  assert.equal((await snapshot()).toggles, 0)
  assert.equal((await snapshot()).menuOpen, false)
  console.log('PASS goal editor keeps slash, file and skill text literal; Enter inserts a newline; no composer menu or submit')
  await key('S', [process.platform === 'darwin' ? 'meta' : 'control'])
  await until('window.goalInteractionFixture.snapshot().saves.length === 1')
  assert.deepEqual((await snapshot()).saves, ['/goal @file $skill\nSecond line'])
  console.log('PASS platform Save shortcut submits the exact multiline objective once')
  let toggles = 0
  for (const sessionId of ['existing-local-thread', null]) {
    const result = await read(`window.goalInteractionFixture.activateSlash(${JSON.stringify(sessionId)})`)
    assert.deepEqual(result, { activated: true, draft: 'Complete the authored objective', armed: true, enableCalls: 1, sessionId })
    await read('window.goalInteractionFixture.openMenu()')
    await until('Array.from(document.querySelectorAll("#composer-plus-menu button")).some(button => button.textContent.includes("Goal"))')
    await read('Array.from(document.querySelectorAll("#composer-plus-menu button")).find(button => button.textContent.includes("Goal")).click()')
    toggles++
    await until(`window.goalInteractionFixture.snapshot().toggles === ${toggles}`)
    await read('window.goalInteractionFixture.closeMenu()')
  }
  console.log('PASS plus and slash entries arm existing-local and new-worktree drafts without creating a session')
  assert.equal((await snapshot()).goalEnabled, false)
  await read('window.goalInteractionFixture.closeMenu(); document.querySelector("#side-input").focus()')
  await window.webContents.insertText('/goal Side conversation text')
  await pause()
  assert.equal(await read('document.querySelector("#side-input").value'), '/goal Side conversation text')
  assert.equal((await snapshot()).sideWorkflowControls, 0)
  assert.equal((await snapshot()).toggles, 2)
  console.log('PASS side clone exposes no goal/slash controls and retains slash text as its own message')
  await read('document.querySelector("#resume-fixture [data-goal-action=resume]").click()')
  await until('document.querySelector("#resume-fixture [role=dialog]")')
  assert.equal(await read('document.querySelector("#resume-fixture [role=dialog]").textContent.includes(window.goalInteractionFixture.snapshot().fullResumeObjective)'), true)
  assert.equal(await read('document.querySelector("#resume-fixture [role=dialog]").textContent.includes("/owned/goal/objective.md")'), false)
  await key('Escape')
  await until('!document.querySelector("#resume-fixture [role=dialog]")')
  assert.equal((await snapshot()).resumes, 0)
  await read('document.querySelector("#resume-fixture [data-goal-action=resume]").click()')
  await until('document.querySelector("#resume-fixture [role=dialog]")')
  await read('window.goalInteractionFixture.advanceResumeAccounting()')
  await read('Array.from(document.querySelectorAll("#resume-fixture [role=dialog] button")).find(button => button.textContent === "Resume goal").click()')
  await until('window.goalInteractionFixture.snapshot().resumes === 1')
  console.log('PASS resume previews full saved objective, Escape preserves pause, accounting updates retain source-bound confirmation')
  await read('window.goalInteractionFixture.restrictMenu(); window.goalInteractionFixture.openMenu()')
  await until('window.goalInteractionFixture.snapshot().menuOpen')
  assert.equal(await read('Array.from(document.querySelectorAll("#composer-plus-menu button")).some(button => button.textContent.includes("Goal"))'), false)
  await read('window.goalInteractionFixture.closeMenu()')
  await until('document.querySelector("#restricted-editor .cm-content")')
  assert.equal(await read('document.querySelector("#restricted-editor .cm-content").getAttribute("contenteditable")'), 'false')
  await read('document.querySelector("#restricted-editor [data-goal-editor]").focus()')
  assert.equal(await read('document.activeElement.closest("#restricted-editor") !== null'), true)
  await window.webContents.insertText('Unexpected edit')
  await key('S', [process.platform === 'darwin' ? 'meta' : 'control'])
  await pause()
  assert.equal((await snapshot()).restrictedText, 'Legacy saved objective')
  assert.deepEqual((await snapshot()).restrictedSaves, [])
  assert.equal(await read('Array.from(document.querySelectorAll("#restricted-editor button")).find(button => button.textContent === "Save").disabled'), true)
  assert.equal(await read('!!document.querySelector("#restricted-goal [data-goal-action=edit], #restricted-goal [data-goal-action=resume]")'), false)
  await read('document.querySelector("#restricted-goal [data-goal-action=open]").click()')
  await read('document.querySelector("#restricted-goal [data-goal-action=pause]").click()')
  await until('window.goalInteractionFixture.snapshot().restrictedPauses === 1')
  assert.equal(await read('!!document.querySelector("#restricted-goal [data-goal-action=resume]")'), false)
  await read('document.querySelector("#restricted-goal [data-goal-action=clear]").click()')
  await until('window.goalInteractionFixture.snapshot().restrictedClears === 1')
  assert.equal((await snapshot()).restrictedOpens, 1)
  assert.equal((await snapshot()).restrictedResumes, 0)
  assert.equal((await snapshot()).toggles, 2)
  console.log('PASS bounded goal hides pursuit entry/edit/resume, keeps read/pause/clear, and readonly editor rejects typing and Save')
}
function finish(code) {
  window?.destroy()
  rmSync(directory, { recursive: true, force: true })
  app.exit(code)
}
run().then(() => { console.log('Goal interaction fixture: 6 passed, 0 failed'); finish(0) }, error => { console.error(error); finish(1) })
