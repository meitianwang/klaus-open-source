export const projectCoverIconCatalog: ProjectCoverIcon[] = groups.flatMap(([ids, en, zh, keywords, svg]) => ids.split(' ').map((id, index) => ({
  id, en: `${en}${index ? ` ${index + 1}` : ''}`, zh: `${zh}${index ? ` ${index + 1}` : ''}`, keywords,
  svg: svg.replace('<svg ', `<svg${index ? ` stroke="currentColor" stroke-width="${index % 2 ? 6 : 11}" stroke-linejoin="round"` : ''} `),
}))).sort((a, b) => presetOrder.indexOf(a.id) - presetOrder.indexOf(b.id))
export function searchProjectCoverIcons(query: string): ProjectCoverIcon[] {
  const search = query.trim().toLocaleLowerCase()
  return projectCoverIconCatalog.filter(icon => !search || `${icon.id} ${icon.en} ${icon.zh} ${icon.keywords}`.toLocaleLowerCase().includes(search))
}
export function randomProjectCoverIcon(current: string, value = Math.random()): string {
  const options = projectCoverIconCatalog.filter(icon => icon.id !== current)
  return options[Math.min(options.length - 1, Math.max(0, Math.floor(value * options.length)))]!.id
}
