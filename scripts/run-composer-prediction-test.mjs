import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { mkdirSync, writeFileSync } from 'node:fs';
import { spawnElectronGui } from './electron-test-preflight.cjs';
const desktop = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const output = join(desktop, 'dist/prediction-logs');
const fixture = join(output, 'fixture');
mkdirSync(fixture, { recursive: true });
await require('esbuild').build({ entryPoints: [join(desktop, 'tests/composer-prediction-dom-entry.tsx')], outfile: join(fixture, 'browser.js'), bundle: true, platform: 'browser', format: 'iife', logLevel: 'silent' });
writeFileSync(join(fixture, 'index.html'), `<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="${pathToFileURL(join(desktop, 'frontend/css/styles.css'))}"><style>body{display:block;padding:80px 100px}main{position:relative;border:1px solid var(--border);border-radius:18px;padding:18px;width:650px}#slash-input-line{min-height:90px}</style></head><body><script src="browser.js"></script></body></html>`);
const env = { ...process.env, KLAUS_PREDICTION_TEST_ROOT: output };
delete env.ELECTRON_RUN_AS_NODE;
const args = [join(desktop, 'tests/composer-prediction-electron.cjs')];
const log = [`$ ${JSON.stringify([require('electron'), ...args])}\n`];
const child = spawnElectronGui(require('electron'), args, { env, stdio: ['ignore', 'pipe', 'pipe'] });
for (const stream of [child.stdout, child.stderr]) stream.on('data', chunk => { log.push(String(chunk)); process.stdout.write(chunk) });
const timer = setTimeout(() => child.kill('SIGTERM'), 60_000);
const code = await new Promise((resolve, reject) => { child.once('error', reject); child.once('close', resolve) });
clearTimeout(timer); log.push(`\nexit_code=${code}\n`); writeFileSync(join(output, 'editor.log'), log.join(''));
process.exitCode = code === 0 ? 0 : 1;
