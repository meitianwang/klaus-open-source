const { app, BrowserWindow } = require('electron')
const { strict: assert } = require('node:assert')
const fs = require('node:fs')
const path = require('node:path')
const root = process.env.KLAUS_LIFECYCLE_TEST_ROOT
app.setPath('userData', path.join(root, 'profile'))
let win
const checks = []
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const evaluate = value => win.webContents.executeJavaScript(value, true)
const snapshot = () => evaluate('lifecycleFixture.snapshot()')
async function click(selector) {
  const point = await evaluate(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});if(!el)throw Error('Missing control: '+${JSON.stringify(selector)});el.scrollIntoView({block:'center'});const r=el.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  for (const type of ['mousePressed', 'mouseReleased']) await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type, ...point, button: 'left', clickCount: 1 })
  await wait(380)
}
async function screenshot(name) { fs.writeFileSync(path.join(root, name + '.png'), (await win.webContents.capturePage()).toPNG()) }
async function hover(selector) {
  const point = await evaluate(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});el.scrollIntoView({block:'center'});const r=el.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', ...point })
  await wait(250)
}
