  state = await snapshot(); assert.equal(state.references[0].kind, 'plugin'); assert.equal(state.references[0].id, 'review-tools')
  console.log('PASS typed multiword searches rank plugin aliases and preserve the selected resource identity')
  await text(''); await click('#main-plus'); await window.webContents.insertText('Skill')
