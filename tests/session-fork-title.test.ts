// Host contract for conversation branching titles.
//
// The renderer strips a trailing "· Branch" off forked titles (sidebar, titlebar,
// command menu) and shows a branch icon plus a fork-provenance banner instead, so
// the stored title is the only place raw consumers (exports, mobile, the engine's
// own title surface) can learn a row is a branch. The suffix therefore belongs to
// the host's fork path, and re-forking a branch must not stack it.
//
// The fake engine client answers `session/forkSession` with the branch id it was
// handed, which a static scripted reply cannot do: the branch id is generated
// inside `forkSession`.

import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { EventEmitter } from 'node:events';

import { assertEqual, Harness } from './harness';
import { HostState } from '../main/services/host-state';
import { SessionService, type EngineAttacherLike, type EngineClientLike } from '../main/sessions/service';
import { kvSet, withSettingsDb } from '../main/services/settings';
import type { Json } from '../main/ipc/contract';
import { FakeEngineQueue } from './engine-queue-fixture';

const h = new Harness();

process.env.KLAUS_TEST = '1';
const roots: string[] = [];
function byoRoot(): string {
  const root = mkdtempSync(join(tmpdir(), 'klaus-fork-title-'));
  roots.push(root);
  assertEqual(kvSet('auth_mode', 'custom', root), true, 'the BYO precondition was written');
  return root;
}

class ForkFakeClient extends EventEmitter implements EngineClientLike {
  readonly queue = new FakeEngineQueue();
  readonly calls: Array<{ method: string; params: Json }> = [];
  closed = false;

  constructor(private readonly sourceTitle: string) {
    super();
  }

  isClosed(): boolean {
    return this.closed;
  }

  sent(method: string): Json[] {
    return this.calls.filter((call) => call.method === method).map((call) => call.params);
  }

  async requestWithTimeout(method: string, params: Json): Promise<unknown> {
    this.calls.push({ method, params });
    if (method.startsWith('thread/queue/')) return this.queue.request(method, params);
    const ack = (envelope: Record<string, unknown>) => {
      this.emit('event', { type: 'engineEvent', params: { submissionId: 'fixture-submission', ...envelope } });
      return { submissionId: 'fixture-submission' };
    };
    switch (method) {
      case 'session/start': return { sessionId: 'engine-branch' };
      // The branch identity is generated by the host per call, so the acknowledgement
      // has to echo what the request carried.
      case 'session/forkSession': {
        const record = params as Record<string, Json>;
        return ack({ session: { threadId: record.newThreadId } });
      }
      case 'session/updateThreadHostMetadata': return ack({ hostMetadataUpdated: true });
      case 'session/updateTitle': return ack({ title: (params as Record<string, Json>).title });
      case 'session/prepare': return { sessionId: (params as { sessionId: string }).sessionId, ready: true };
      case 'session/subscribe': return { subscribed: true };
      case 'session/taskList': return { tasks: [] };
      case 'session/queueSnapshot': return { queueSnapshot: { revision: 0, items: [], status: 'authoritative' } };
      case 'session/resumePending': return { pendingResume: { started: false, reason: 'empty' } };
      case 'session/setupLifecycle': return { setupLifecycle: { idempotencyResults: {} } };
      case 'session/subagentLifecycle': return { subagentLifecycle: { agents: [] } };
      case 'session/backgroundProcesses': return { backgroundProcesses: { processes: [] } };
      case 'config/read': return { resolved: {}, sources: {} };
      case 'model/selection/resolve': return { source: 'custom', selection: 'custom:fixture-default' };
      case 'engine/listSessions':
        return { sessions: { items: [{ id: 'source', createdAt: 1, updatedAt: 2, title: this.sourceTitle }], nextCursor: null } };
      case 'engine/readSessionSummary':
        return { session: (params as Record<string, Json>).sessionId === 'source'
          ? { id: 'source', createdAt: 1, updatedAt: 2, title: this.sourceTitle } : null };
      default: throw new Error(`fake client: no reply scripted for ${method}`);
    }
  }
}

function serviceWith(client: ForkFakeClient, configRoot: string): SessionService {
  const manager: EngineAttacherLike = {
    attach: async () => ({ client, generation: 1 }),
    shutdownAll: async () => { client.closed = true; },
  };
  return new SessionService({
    manager,
    state: new HostState(),
    spawnOptions: () => ({ command: '/bin/true', args: [], env: [] }),
    pushChatEvents: () => {},
    configRoot,
  });
}

h.test('a branch title carries the visible suffix and the raw source title as provenance', async () => {
  const client = new ForkFakeClient('Retained source title');
  const service = serviceWith(client, byoRoot());
  const fork = await service.forkSession('source') as Record<string, Json>;
  assertEqual(fork.title, 'Retained source title · Branch', 'the stored branch title says it is a branch');
  const provenance = fork.forkedFrom as Record<string, Json>;
  assertEqual(provenance.sessionId, 'source', 'provenance points at the source conversation');
  assertEqual(provenance.title, 'Retained source title', 'provenance keeps the raw source title for the banner');
  const titleUpdate = client.sent('session/updateTitle')[0] as Record<string, Json>;
  assertEqual(titleUpdate.title, 'Retained source title · Branch', 'the engine title surface receives the suffixed title');
  const metadata = client.sent('session/updateThreadHostMetadata')[0] as Record<string, Json>;
  assertEqual((metadata.hostMetadata as Record<string, Json>).forkedFrom != null, true, 'fork provenance is persisted as host metadata');
});

h.test('re-forking a branch never stacks the suffix', async () => {
  // The source itself is already a branch: its stored title carries the suffix.
  const client = new ForkFakeClient('Retained source title · Branch');
  const service = serviceWith(client, byoRoot());
  const fork = await service.forkSession('source') as Record<string, Json>;
  assertEqual(fork.title, 'Retained source title · Branch', 'one suffix, however many times the line is branched');
  const provenance = fork.forkedFrom as Record<string, Json>;
  assertEqual(provenance.title, 'Retained source title', 'provenance shows the display title, not a suffixed one');
});

function seedLedgerTitle(root: string, title: string, source: string): void {
  withSettingsDb(root, db => {
    db.exec(`CREATE TABLE IF NOT EXISTS session_titles (
      session_id TEXT PRIMARY KEY, title TEXT, source TEXT, ai_title_attempted_at INTEGER, updated_at INTEGER NOT NULL
    )`);
    db.prepare('INSERT INTO session_titles VALUES (?, ?, ?, ?, ?)').run('source', title, source, null, 1);
  });
}

h.test('a title that lives only in the host ledger is inherited by the branch', async () => {
  // Seeding writes the visible title to the host ledger immediately; the engine row
  // stays empty until generation persists there, and an interrupted turn can leave
  // the ledger as the only title holder. The branch must not fall back to the bare
  // placeholder in that state.
  const root = byoRoot();
  seedLedgerTitle(root, 'Ledger-only source title', 'seed');
  const client = new ForkFakeClient('');
  const service = serviceWith(client, root);
  const fork = await service.forkSession('source') as Record<string, Json>;
  assertEqual(fork.title, 'Ledger-only source title · Branch', 'the branch inherits the visible ledger title');
  const provenance = fork.forkedFrom as Record<string, Json>;
  assertEqual(provenance.title, 'Ledger-only source title', 'provenance shows the ledger title, not the placeholder');
});

h.test('an explicit ledger title wins over a stale engine title, matching the session list', async () => {
  const root = byoRoot();
  seedLedgerTitle(root, 'Renamed in ledger', 'custom');
  const client = new ForkFakeClient('Stale engine title');
  const service = serviceWith(client, root);
  const fork = await service.forkSession('source') as Record<string, Json>;
  assertEqual(fork.title, 'Renamed in ledger · Branch', 'the branch resolves titles like the projected session list');
});

void (async () => {
  const failed = await h.finish(join(__dirname, 'session-fork-title-result.json'), 'session-fork-title');
  for (const root of roots) {
    try {
      rmSync(root, { recursive: true, force: true });
    } catch {
      // A temp dir that will not delete is not a test failure.
    }
  }
  process.exit(failed);
})();
