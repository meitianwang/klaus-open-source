const { app, BrowserWindow } = require('electron')
const { join } = require('node:path')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const output = process.argv[2]
const profile = mkdtempSync(join(tmpdir(), 'klaus-storage-settings-'))
app.setPath('userData', profile)
const timer = setTimeout(() => { console.error('Storage settings fixture timed out'); app.exit(1) }, 60000)
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1280, height: 1000, webPreferences: { sandbox: true, contextIsolation: true, backgroundThrottling: false } })
  try {
    await window.loadFile(join(output, 'index.html'))
    await window.webContents.executeJavaScript('window.storageSettingsReady')
    const point = await window.webContents.executeJavaScript('window.storageSettingsOpenReview()')
    window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point })
    window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point })
    await window.webContents.executeJavaScript('window.storageSettingsReviewVisible()')
    writeFileSync(join(output, 'review.png'), (await window.webContents.capturePage()).toPNG())
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' })
    await window.webContents.executeJavaScript('window.storageSettingsAfterEscape()')
    const result = await window.webContents.executeJavaScript('window.storageSettingsRun()')
    writeFileSync(join(output, 'results.json'), JSON.stringify(result, null, 2))
    console.log(`Storage settings: ${result.passed} checks passed`)
    app.exit(0)
  } catch (error) {
    console.error(error?.stack || String(error))
    const result = await window.webContents.executeJavaScript('({ body: document.body.innerText, dialogs: [...document.querySelectorAll("dialog")].map(node => ({ open: node.open, modal: node.matches(":modal"), text: node.innerText })) })')
    writeFileSync(join(output, 'failure.json'), JSON.stringify(result, null, 2))
    writeFileSync(join(output, 'failure.png'), (await window.webContents.capturePage()).toPNG())
    app.exit(1)
  } finally { clearTimeout(timer) }
}).catch(error => { console.error(error); app.exit(1) })
process.on('exit', () => { try { rmSync(profile, { recursive: true, force: true }) } catch {} })
