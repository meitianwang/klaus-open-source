  test('stages only the metadata-resolved binary and binds its contents to the manifest', async () => {
    const cargo = await import('./cargo-target-directory.mjs')
    const release = await import('./prepare-rust-release.mjs')
    const fixtureRoot = createTemporaryDirectory('klaus-release-stage-')
    createPolicyNoticeFixture(fixtureRoot)
    const target = release.resolveReleaseTarget('darwin', 'arm64')
    const customTargetDirectory = join(fixtureRoot, 'custom-target')
    const customBinary = cargo.cargoReleaseBinaryPath({
      targetDirectory: customTargetDirectory,
      targetTriple: target.targetTriple,
      binaryName: target.binary,
    })
    const poisonBinary = join(
      fixtureRoot,
      'engine/klaus-agent-rust/target',
      target.targetTriple,
      'release',
      target.binary,
    )
    mkdirSync(dirname(customBinary), { recursive: true })
    mkdirSync(dirname(poisonBinary), { recursive: true })
    writeFileSync(customBinary, 'custom-release-binary')
    writeFileSync(poisonBinary, 'poison-stale-binary')

    const engineCommit = 'e'.repeat(40)
    const sourceFingerprint = { version: 1, sha256: 'f'.repeat(64), fileCount: 3 }
    const staged = release.stageRelease({
      repoRoot: fixtureRoot,
      target,
      engineCommit,
      sourceFingerprint,
      sourceBinary: customBinary,
    })

    expect(readFileSync(staged.destinationBinary, 'utf8')).toBe('custom-release-binary')
    expect(staged.manifest.sha256).toBe(
      createHash('sha256').update('custom-release-binary').digest('hex'),
    )
    expect(staged.manifest.sha256).not.toBe(
      createHash('sha256').update('poison-stale-binary').digest('hex'),
    )
    const stagedState = release.readStagedRelease(fixtureRoot, target)
    expect(stagedState?.contentsMatchManifest).toBe(true)
    expect(stagedState?.sourceFingerprint).toEqual(sourceFingerprint)
    expect(release.planEngineStaging({
      mode: 'dev', indexedCommit: engineCommit, checkoutCommit: engineCommit,
      treeDirty: false, sourceFingerprint, staged: stagedState,
    }).action).toBe('reuse')
    unlinkSync(join(dirname(staged.destinationBinary), 'licenses/goal-policy/NOTICE'))
    const missingNotice = release.readStagedRelease(fixtureRoot, target)
    expect(missingNotice?.contentsMatchManifest).toBe(false)
    expect(release.planEngineStaging({
      mode: 'dev', indexedCommit: engineCommit, checkoutCommit: engineCommit,
      treeDirty: false, sourceFingerprint, staged: missingNotice,
    }).reason).toBe('staged engine artifacts do not hash to their manifest')

    unlinkSync(customBinary)
    expect(() => release.stageRelease({
      repoRoot: fixtureRoot,
      target,
      engineCommit,
      sourceBinary: customBinary,
    })).toThrow(`Cargo release binary not found at resolved path: ${customBinary}`)
    expect(readFileSync(poisonBinary, 'utf8')).toBe('poison-stale-binary')
  })

  test('replaces the staged binary through a new inode instead of overwriting it in place', async () => {
    const cargo = await import('./cargo-target-directory.mjs')
    const release = await import('./prepare-rust-release.mjs')
    const fixtureRoot = createTemporaryDirectory('klaus-release-inode-')
    createPolicyNoticeFixture(fixtureRoot)
    const target = release.resolveReleaseTarget('darwin', 'arm64')
    const sourceBinary = cargo.cargoReleaseBinaryPath({
      targetDirectory: join(fixtureRoot, 'custom-target'),
      targetTriple: target.targetTriple,
      binaryName: target.binary,
    })
    mkdirSync(dirname(sourceBinary), { recursive: true })
    writeFileSync(sourceBinary, 'first-release-binary')

    const engineCommit = 'f'.repeat(40)
    const first = release.stageRelease({
      repoRoot: fixtureRoot,
      target,
      engineCommit,
      sourceBinary,
    })
    const firstInode = statSync(first.destinationBinary).ino

    writeFileSync(sourceBinary, 'second-release-binary')
    const second = release.stageRelease({
      repoRoot: fixtureRoot,
      target,
      engineCommit,
      sourceBinary,
    })

    // A plain in-place copy would keep the inode and rewrite its pages, which is
    // what invalidates macOS's per-inode code-signature cache and gets every
    // later exec of the engine SIGKILLed by taskgated. Staging must land on a
    // NEW inode so a process still mapping the old one is untouched.
    expect(statSync(second.destinationBinary).ino).not.toBe(firstInode)
    expect(readFileSync(second.destinationBinary, 'utf8')).toBe('second-release-binary')
    expect(statSync(second.destinationBinary).mode & 0o777).toBe(0o755)
    // No staging leftovers next to the destination.
    expect(
      readdirSync(dirname(second.destinationBinary)).filter(name => name.includes('.staging-')),
    ).toEqual([])
  })

