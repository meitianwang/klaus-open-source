    run('git', ['add', 'Cargo.toml', 'src/lib.rs'], dependencyRoot)
    run('git', ['-c', 'user.name=Build fixture', '-c', 'user.email=build-fixture@example.invalid',
      '-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=', 'commit', '-qm', 'Add dependency fixture'], dependencyRoot)
