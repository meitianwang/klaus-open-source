import { afterEach, describe, expect, test } from 'bun:test'
import { execFileSync } from 'node:child_process'
import { chmodSync, mkdirSync, mkdtempSync, renameSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { assertEngineSourceUnchanged, buildReleaseManifest, fingerprintEngineSource, planEngineStaging, resolveReleaseTarget } from './prepare-rust-release.mjs'

const directories: string[] = []
afterEach(() => { for (const path of directories.splice(0)) rmSync(path, { recursive: true, force: true }) })

function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'klaus-engine-source-'))
  directories.push(root)
  mkdirSync(join(root, 'src'))
  writeFileSync(join(root, '.gitignore'), '/target\n*.ignored\n')
  writeFileSync(join(root, 'Cargo.toml'), '[package]\nname = "source-fixture"\nversion = "0.1.0"\n')
  writeFileSync(join(root, 'src/main.rs'), 'fn main() {}\n')
  execFileSync('git', ['init', '--quiet', root])
  execFileSync('git', ['-C', root, 'add', '--', '.gitignore', 'Cargo.toml', 'src/main.rs'])
  return root
}

describe('development engine source fingerprint', () => {
  test('is independent of checkout location and ignores generated untracked output', () => {
    const first = fixture(), second = fixture(), before = fingerprintEngineSource(first)
    expect(before).toEqual(fingerprintEngineSource(second))
    expect(before.fileCount).toBe(3)
    mkdirSync(join(first, 'target'))
    writeFileSync(join(first, 'target/generated'), 'generated bytes')
    writeFileSync(join(first, 'local.ignored'), 'local bytes')
    expect(fingerprintEngineSource(first)).toEqual(before)
    writeFileSync(join(first, 'tracked.ignored'), 'tracked build input')
    execFileSync('git', ['-C', first, 'add', '--force', '--', 'tracked.ignored'])
    expect(fingerprintEngineSource(first)).not.toEqual(before)
  })

  test('tracked edits and deletion change identity even when HEAD is unchanged', () => {
    const root = fixture(), before = fingerprintEngineSource(root), source = join(root, 'src/main.rs')
    writeFileSync(source, 'fn main() { println!("edited"); }\n')
    expect(fingerprintEngineSource(root)).not.toEqual(before)
    unlinkSync(source)
    const deleted = fingerprintEngineSource(root)
    expect(deleted).not.toEqual(before)
    expect(deleted.fileCount).toBe(before.fileCount)
    writeFileSync(source, 'fn main() {}\n')
    expect(fingerprintEngineSource(root)).toEqual(before)
  })

  test('untracked additions, changes, renames and removals change identity', () => {
    const root = fixture(), before = fingerprintEngineSource(root), source = join(root, 'new.rs')
    writeFileSync(source, 'first')
    const added = fingerprintEngineSource(root)
    expect(added.fileCount).toBe(before.fileCount + 1)
    expect(added).not.toEqual(before)
    writeFileSync(source, 'other')
    expect(fingerprintEngineSource(root)).not.toEqual(added)
    renameSync(source, join(root, 'renamed.rs'))
    expect(fingerprintEngineSource(root)).not.toEqual(added)
    unlinkSync(join(root, 'renamed.rs'))
    expect(fingerprintEngineSource(root)).toEqual(before)
  })

  test.skipIf(process.platform === 'win32')('file modes and symlink paths, targets and contents are bound', () => {
    const root = fixture(), before = fingerprintEngineSource(root), source = join(root, 'src/main.rs')
    chmodSync(source, 0o755)
    expect(fingerprintEngineSource(root)).not.toEqual(before)
    chmodSync(source, 0o644)
    expect(fingerprintEngineSource(root)).toEqual(before)
    writeFileSync(join(root, 'first.ignored'), 'same')
    writeFileSync(join(root, 'other.ignored'), 'same')
    const link = join(root, 'linked.rs')
    symlinkSync('first.ignored', link)
    const linked = fingerprintEngineSource(root)
    writeFileSync(join(root, 'first.ignored'), 'changed')
    expect(fingerprintEngineSource(root)).not.toEqual(linked)
    writeFileSync(join(root, 'first.ignored'), 'same')
    unlinkSync(link); symlinkSync('other.ignored', link)
    expect(fingerprintEngineSource(root)).not.toEqual(linked)
    unlinkSync(link); symlinkSync('missing.rs', link)
    expect(fingerprintEngineSource(root)).not.toEqual(linked)
    unlinkSync(link); symlinkSync('../outside.rs', link)
    expect(() => fingerprintEngineSource(root)).toThrow('escapes its source root')
    unlinkSync(link); symlinkSync('src', link)
    expect(() => fingerprintEngineSource(root)).toThrow('must target a regular file')
  })

  test('the build boundary rejects changed source, commit or dirty state', () => {
    const root = fixture()
    const before = { commit: 'a'.repeat(40), dirty: true, sourceFingerprint: fingerprintEngineSource(root) }
    expect(() => assertEngineSourceUnchanged(before, before)).not.toThrow()
    writeFileSync(join(root, 'new.rs'), 'changed during build')
    expect(() => assertEngineSourceUnchanged(before, { ...before, sourceFingerprint: fingerprintEngineSource(root) })).toThrow('changed during the development build')
    expect(() => assertEngineSourceUnchanged(before, { ...before, commit: 'b'.repeat(40) })).toThrow()
    expect(() => assertEngineSourceUnchanged(before, { ...before, dirty: false })).toThrow()
  })
})

describe('development artifact source admission', () => {
  const commit = 'a'.repeat(40)
  const sourceFingerprint = { version: 1, sha256: 'f'.repeat(64), fileCount: 3 }
  const staged = { engineCommit: commit, treeDirty: true, sourceFingerprint, releaseFlags: 'flags', contentsMatchManifest: true }
  const options = { mode: 'dev', indexedCommit: commit, checkoutCommit: commit, treeDirty: true, sourceFingerprint, releaseFlags: 'flags', staged }

  test('only matching commit, full source, dirty state, flags and artifact bytes allow reuse', () => {
    expect(planEngineStaging(options)).toMatchObject({ action: 'reuse', treeDirty: true })
    expect(planEngineStaging({ ...options, treeDirty: false, staged: { ...staged, treeDirty: false } }).action).toBe('reuse')
    for (const candidate of [
      { ...staged, engineCommit: 'b'.repeat(40) },
      { ...staged, treeDirty: false },
      { ...staged, treeDirty: undefined },
      { ...staged, sourceFingerprint: undefined },
      { ...staged, sourceFingerprint: { ...sourceFingerprint, sha256: 'e'.repeat(64) } },
      { ...staged, sourceFingerprint: { ...sourceFingerprint, fileCount: 4 } },
      { ...staged, sourceFingerprint: { ...sourceFingerprint, version: 2 } },
      { ...staged, sourceFingerprint: { ...sourceFingerprint, sha256: 'invalid' } },
      { ...staged, sourceFingerprint: { ...sourceFingerprint, extra: true } },
      { ...staged, releaseFlags: 'other-flags' },
      { ...staged, contentsMatchManifest: false },
    ]) expect(planEngineStaging({ ...options, staged: candidate }).action).toBe('build')
    expect(planEngineStaging({ ...options, sourceFingerprint: undefined }).action).toBe('build')
  })

  test('packaging still refuses dirty artifacts and retains clean indexed-artifact reuse', () => {
    expect(planEngineStaging({ ...options, mode: 'package' }).action).toBe('build')
    expect(planEngineStaging({ ...options, mode: 'package', checkoutCommit: 'b'.repeat(40), staged: { ...staged, treeDirty: false, sourceFingerprint: undefined } }).action).toBe('reuse')
    expect(planEngineStaging({ ...options, mode: 'package', checkoutCommit: 'b'.repeat(40), staged: { ...staged, treeDirty: false, engineCommit: 'b'.repeat(40) } }).action).toBe('build')
  })

  test('macOS and Windows manifests preserve the source proof and genuine dirty label', () => {
    for (const [platform, arch] of [['darwin', 'arm64'], ['win32', 'x64']]) {
      const target = resolveReleaseTarget(platform, arch)
      const input = { engineCommit: commit, treeDirty: true, sourceFingerprint, target, binaryContents: Buffer.from('engine'), artifactContents: new Map((target.artifacts ?? []).map(({ role }) => [role, Buffer.from(role)])) }
      expect(buildReleaseManifest(input)).toMatchObject({ engineTreeDirty: true, engineSourceFingerprint: sourceFingerprint })
      expect(() => buildReleaseManifest({ ...input, sourceFingerprint: { ...sourceFingerprint, sha256: 'invalid' } })).toThrow('Invalid engine source fingerprint')
    }
  })
})
